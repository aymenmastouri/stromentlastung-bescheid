-- Bescheide (Fachkonzept Kap. 8): Daten als JSON, PDF und Hash nach dem Rendern.
CREATE TABLE bescheid (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kennung              VARCHAR(48)   NOT NULL UNIQUE,
    aktenzeichen         VARCHAR(40)   NOT NULL,
    unternehmen_kennung  VARCHAR(12)   NOT NULL,
    dienststelle         VARCHAR(8)    NOT NULL,
    art                  VARCHAR(12)   NOT NULL,
    entnahmejahr         INT           NOT NULL,
    datum                DATE          NOT NULL,
    absendung            DATE          NOT NULL,
    bekanntgabe          DATE          NOT NULL,
    betrag_cent          BIGINT        NOT NULL,
    rueckforderung_cent  BIGINT,
    faelligkeit          DATE,
    gruende              VARCHAR(1000) NOT NULL,
    zitate               VARCHAR(2000) NOT NULL,
    daten                CLOB          NOT NULL,
    textbaustein_version VARCHAR(8)    NOT NULL,
    pdf                  BLOB,
    hash                 VARCHAR(64),
    gelesen_am           TIMESTAMP WITH TIME ZONE,
    erstellt_am          TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_bescheid_aktenzeichen ON bescheid (aktenzeichen);
CREATE INDEX ix_bescheid_unternehmen ON bescheid (unternehmen_kennung);
